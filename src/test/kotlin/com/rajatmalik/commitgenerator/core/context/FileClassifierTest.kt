package com.rajatmalik.commitgenerator.core.context

import com.rajatmalik.commitgenerator.core.domain.ChangeStatus
import com.rajatmalik.commitgenerator.core.domain.FileChange
import com.rajatmalik.commitgenerator.core.domain.DiffHunk
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

class FileClassifierTest {
    @Test
    fun `classifies lockfiles generated and assets as not important`() {
        assertFalseImportant("package-lock.json")
        assertFalseImportant("dist/app.js")
        assertFalseImportant("logo.png")
        assertFalseImportant("src/generated/api.g.ts")
    }

    @Test
    fun `classifies source tests docs and configs as important`() {
        assertTrue(classifyPath("src/main/kotlin/App.kt").important)
        assertEquals(FileCategory.SOURCE, classifyPath("src/main/kotlin/App.kt").category)
        assertEquals(FileCategory.TEST, classifyPath("src/test/kotlin/AppTest.kt").category)
        assertEquals(FileCategory.DOCUMENTATION, classifyPath("README.md").category)
        assertEquals(FileCategory.CONFIG, classifyPath("package.json").category)
    }

    @Test
    fun `generated marker overrides a source path`() {
        val classification = classifyFile(
            "src/main/kotlin/Generated.kt",
            isBinary = false,
            hunkLines = listOf(listOf("// @generated by tool")),
        )
        assertEquals(FileCategory.GENERATED, classification.category)
    }

    private fun assertFalseImportant(path: String) {
        assertTrue(!classifyPath(path).important, path)
    }
}
