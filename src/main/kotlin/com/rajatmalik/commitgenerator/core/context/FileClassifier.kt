package com.rajatmalik.commitgenerator.core.context

enum class FileCategory(val key: String) {
    SOURCE("source"),
    TEST("test"),
    DOCUMENTATION("documentation"),
    CONFIG("config"),
    LOCKFILE("lockfile"),
    GENERATED("generated"),
    BINARY("binary"),
    ASSET("asset"),
    OTHER("other"),
}

data class FileClassification(
    val category: FileCategory,
    val important: Boolean,
    val reason: String? = null,
)

private val LOCKFILES = setOf(
    "package-lock.json",
    "npm-shrinkwrap.json",
    "pnpm-lock.yaml",
    "yarn.lock",
    "bun.lockb",
    "cargo.lock",
    "poetry.lock",
    "pipfile.lock",
    "composer.lock",
    "gemfile.lock",
    "go.sum",
    "deno.lock",
    "mix.lock",
    "podfile.lock",
    "packages.lock.json",
)

private val LOCKFILE_PATTERN = Regex("(^|/)(.*\\.lock|.*-lock\\.json)$", RegexOption.IGNORE_CASE)

private val GENERATED_SEGMENTS = listOf(
    "node_modules/", "dist/", "build/", "out/", "vendor/", "coverage/",
    ".next/", ".nuxt/", "__generated__/", "generated/",
)

private val GENERATED_SUFFIXES = listOf(
    ".min.js", ".min.css", ".map", ".snap", ".generated.ts", ".generated.js", ".g.ts", ".g.dart",
)

private val ASSET_EXTENSIONS = listOf(
    ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".bmp", ".svg", ".pdf",
    ".woff", ".woff2", ".ttf", ".eot", ".mp4", ".webm", ".mp3", ".wav",
    ".zip", ".gz", ".tar",
)

private val TEST_PATTERN = Regex("(^|/)(__tests__|tests?|spec|e2e)/|\\.(test|spec|e2e)\\.[a-z0-9]+$", RegexOption.IGNORE_CASE)
private val DOC_PATTERN = Regex("\\.(md|mdx|rst|adoc|txt)$", RegexOption.IGNORE_CASE)
private val CONFIG_PATTERN = Regex(
    "(^|/)(package\\.json|tsconfig[^/]*\\.json|jsconfig[^/]*\\.json|\\.gitignore|\\.editorconfig|" +
        "\\.eslintrc[^/]*|\\.prettierrc[^/]*|dockerfile|makefile|[^/]*\\.config\\.(js|mjs|cjs|ts))$",
    RegexOption.IGNORE_CASE,
)
private val CONFIG_EXTENSION = Regex("\\.(json|ya?ml|toml|ini|properties|xml)$", RegexOption.IGNORE_CASE)
private val SOURCE_EXTENSION = Regex(
    "\\.(ts|tsx|mts|cts|js|jsx|mjs|cjs|py|go|rs|java|kt|kts|cs|cpp|cc|c|h|hpp|rb|php|swift|scala|" +
        "sh|ps1|sql|vue|svelte|astro|lua|dart|ex|exs|erl|clj|hs|ml|nim|zig|proto|graphql|gql)$",
    RegexOption.IGNORE_CASE,
)

private val GENERATED_MARKERS = listOf(
    "@generated", "do not edit", "auto-generated", "automatically generated",
    "generated by", "this file is generated",
)

private fun baseName(path: String): String = path.substringAfterLast('/').lowercase()

fun classifyPath(path: String): FileClassification {
    val normalized = path.replace('\\', '/').lowercase()
    val name = baseName(normalized)

    if (name in LOCKFILES || LOCKFILE_PATTERN.containsMatchIn(normalized)) {
        return FileClassification(FileCategory.LOCKFILE, false, "lockfile")
    }
    if (GENERATED_SEGMENTS.any { normalized.contains(it) }) {
        return FileClassification(FileCategory.GENERATED, false, "generated directory")
    }
    if (GENERATED_SUFFIXES.any { normalized.endsWith(it) }) {
        return FileClassification(FileCategory.GENERATED, false, "generated artifact")
    }
    if (ASSET_EXTENSIONS.any { normalized.endsWith(it) }) {
        return FileClassification(FileCategory.ASSET, false, "binary asset")
    }
    if (TEST_PATTERN.containsMatchIn(normalized)) {
        return FileClassification(FileCategory.TEST, true)
    }
    if (DOC_PATTERN.containsMatchIn(normalized)) {
        return FileClassification(FileCategory.DOCUMENTATION, true)
    }
    if (CONFIG_PATTERN.containsMatchIn(normalized) || CONFIG_EXTENSION.containsMatchIn(normalized)) {
        return FileClassification(FileCategory.CONFIG, true)
    }
    if (SOURCE_EXTENSION.containsMatchIn(normalized)) {
        return FileClassification(FileCategory.SOURCE, true)
    }
    return FileClassification(FileCategory.OTHER, true)
}

fun classifyFile(
    path: String,
    isBinary: Boolean,
    hunkLines: List<List<String>>,
): FileClassification {
    if (isBinary) {
        return FileClassification(FileCategory.BINARY, false, "binary content")
    }
    val generated = hunkLines.take(3).any { lines ->
        lines.take(20).any { line ->
            val lower = line.lowercase()
            GENERATED_MARKERS.any { lower.contains(it) }
        }
    }
    return if (generated) {
        FileClassification(FileCategory.GENERATED, false, "generated marker")
    } else {
        classifyPath(path)
    }
}
